// Builds the two data files the /quiz page needs. Run with: node scripts/build-quiz-data.mjs
//   js/data/quiz-questions.js  <- data-src/quiz_questions_703.json (the question bank, one row per question)
//   js/data/quiz-data.js       <- a slim copy of the site data: only the words the quiz uses, the words
//                                  tagged in the threads that contain them, those threads, and their authors.
// The quiz page never loads the full word packs. Re-run this after the word list or threads change.
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (f) => fs.readFileSync(path.join(root, f), "utf8");
const TAG = /\[\[([^\]|]+)(?:\|([^\]]+))?\]\]/g;

// ---- question bank ----
const bank = JSON.parse(read("data-src/quiz_questions_703.json").replace(/^﻿/, ""));
const rows = bank.map((q) => {
  if (!/\{[^}]+\}/.test(q.stem) || q.distractors.length !== 3) throw new Error("Bad question: " + q.word);
  return [q.word, q.band, q.character, q.stem, q.pos, q.answer, ...q.distractors];
});
fs.writeFileSync(
  path.join(root, "js/data/quiz-questions.js"),
  "// Generated by scripts/build-quiz-data.mjs from data-src/quiz_questions_703.json. Do not edit by hand.\n" +
    "// [word, band 1-10, character, stem with {target}, pos, answer, distractor x3]\n" +
    "window.QUIZ_QUESTIONS = [\n" + rows.map((r) => " " + JSON.stringify(r)).join(",\n") + "\n];\n"
);

// ---- site data (same load order as index.html, plus every pack) ----
const ctx = { console };
ctx.window = ctx;
vm.createContext(ctx);
const run = (f) => vm.runInContext(read(f), ctx, { filename: f });
run("js/data/characters.js");
fs.readdirSync(path.join(root, "js/data"))
  .filter((f) => /^batch-\d+\.js$/.test(f))
  .sort((a, b) => parseInt(a.match(/\d+/)[0]) - parseInt(b.match(/\d+/)[0]))
  .forEach((f) => run("js/data/" + f));
run("js/data/convos.js");
run("js/data/levels.js");
run("js/data/packs/index.js");
const packIds = ctx.PACK_META.map((p) => p.id).filter((id) => id !== "toefl");
packIds.forEach((id) => run("js/data/packs/" + id + ".js"));
run("js/data/kk.js");

const { VOCAB, KK, CHARACTERS } = ctx;
const allPosts = ctx.POSTS.concat(...packIds.map((id) => (ctx.PACK_POSTS && ctx.PACK_POSTS[id]) || []));

const keysIn = (text) => [...text.matchAll(TAG)].map((m) => m[1]);
const quizWords = new Set(rows.map((r) => r[0]));
for (const w of quizWords) if (!VOCAB[w]) throw new Error('Quiz word not in the site word list: "' + w + '"');

// Threads that contain at least one quiz word.
const posts = allPosts.filter((p) => keysIn(p.text).some((k) => quizWords.has(k)));
const words = new Set(quizWords);
posts.forEach((p) => keysIn(p.text).forEach((k) => { if (VOCAB[k]) words.add(k); }));

const V = {}, K = {};
[...words].sort().forEach((k) => {
  const v = VOCAB[k];
  V[k] = [v.pos, v.zh, v.level, v.ex, v.exZh];
  if (v.w) V[k].push(v.w);                       // display form for phrases, e.g. "a.m."
  if (KK[k]) K[k] = KK[k];
});
const CH = {};
posts.forEach((p) => { const c = CHARACTERS[p.author]; if (c && !CH[p.author]) CH[p.author] = { n: c.name, h: c.handle, a: c.avatar, c: c.color }; });
rows.forEach((r) => { const c = CHARACTERS[r[2]]; if (!c) throw new Error("Unknown character: " + r[2]); if (!CH[r[2]]) CH[r[2]] = { n: c.name, h: c.handle, a: c.avatar, c: c.color }; });

const P = posts.map((p) => {
  const o = { id: p.id, a: p.author, x: p.text, z: p.zh, tp: p.topic };
  if (p.likes) o.l = p.likes;
  if (p.replies) o.r = p.replies;
  return o;
});

const data = { stats: { posts: allPosts.length, words: Object.keys(VOCAB).length }, CH, V, KK: K, P };
fs.writeFileSync(
  path.join(root, "js/data/quiz-data.js"),
  "// Generated by scripts/build-quiz-data.mjs from the site data. Do not edit by hand.\n" +
    "// V: word -> [pos, zh, level 1-3, example, example zh, (display form)]; P: threads that contain quiz words.\n" +
    "window.QUIZ_DATA = " + JSON.stringify(data) + ";\n"
);

const kb = (f) => (fs.statSync(path.join(root, f)).size / 1024).toFixed(0) + " KB";
console.log(`questions ${rows.length} (${kb("js/data/quiz-questions.js")}); words ${Object.keys(V).length}, threads ${P.length} of ${allPosts.length}, characters ${Object.keys(CH).length} (${kb("js/data/quiz-data.js")})`);
